import 'package:flutter/material.dart';

import 'package:barwah_app/features/merchants/domain/entities/merchant_entity.dart';

class MerchantModel extends MerchantEntity {
  const MerchantModel({
    required super.id,
    super.code,
    required super.name,
    required super.nameEn,
    required super.category,
    required super.categoryEn,
    required super.categoryIcon,
    required super.crNumber,
    super.logoUrl,
    super.logoIcon,
    required super.status,
    super.isFeatured = false,
    super.statusTagText,
    super.statusTagTextEn,
    super.location,
    super.locationEn,
    super.delegateName,
    super.delegateNameEn,
    super.deliveryStatus,
    super.deliveryStatusEn,
    required super.adsCount,
    required super.adsCountLabel,
    required super.adsCountLabelEn,
    required super.adsSectionTitle,
    required super.adsSectionTitleEn,
    required super.adsIcon,
    required super.activityNote,
    required super.activityNoteEn,
    required super.footerStatusText,
    required super.footerStatusTextEn,
    required super.footerStatusIcon,
    super.footerStatusColor,
    required super.actionButtonText,
    required super.actionButtonTextEn,
    super.isSuspended = false,
    super.ownerName,
    super.ownerNameEn,
    super.contactPhone,
    super.contactEmail,
    super.joinedDate,
    super.joinedDateEn,
    super.commissionPercent,
    super.activeAdsCount,
    super.underReviewAdsCount,
    super.pendingReviewCount,
    super.financialWithdrawalAlert,
    super.financialWithdrawalAlertEn,
    super.violationNotice,
    super.violationNoticeEn,
    super.recentAdvertisements = const [],
    super.allAdvertisements = const [],
  });

  factory MerchantModel.fromJson(Map<String, dynamic> json) {
    return MerchantModel(
      id: json['id'] as String,
      code: json['code'] as String?,
      name: json['name'] as String,
      nameEn: json['nameEn'] as String,
      category: json['category'] as String,
      categoryEn: json['categoryEn'] as String,
      categoryIcon: Icons.store,
      crNumber: json['crNumber'] as String,
      logoUrl: json['logoUrl'] as String?,
      status: MerchantStatus.values.firstWhere(
        (e) => e.name == json['status'],
        orElse: () => MerchantStatus.activeVerified,
      ),
      isFeatured: json['isFeatured'] as bool? ?? false,
      statusTagText: json['statusTagText'] as String?,
      statusTagTextEn: json['statusTagTextEn'] as String?,
      location: json['location'] as String?,
      locationEn: json['locationEn'] as String?,
      delegateName: json['delegateName'] as String?,
      delegateNameEn: json['delegateNameEn'] as String?,
      deliveryStatus: json['deliveryStatus'] as String?,
      deliveryStatusEn: json['deliveryStatusEn'] as String?,
      adsCount: json['adsCount'] as int,
      adsCountLabel: json['adsCountLabel'] as String,
      adsCountLabelEn: json['adsCountLabelEn'] as String,
      adsSectionTitle: json['adsSectionTitle'] as String,
      adsSectionTitleEn: json['adsSectionTitleEn'] as String,
      adsIcon: Icons.campaign_outlined,
      activityNote: json['activityNote'] as String,
      activityNoteEn: json['activityNoteEn'] as String,
      footerStatusText: json['footerStatusText'] as String,
      footerStatusTextEn: json['footerStatusTextEn'] as String,
      footerStatusIcon: Icons.check_circle_outline,
      actionButtonText: json['actionButtonText'] as String,
      actionButtonTextEn: json['actionButtonTextEn'] as String,
      isSuspended: json['isSuspended'] as bool? ?? false,
      ownerName: json['ownerName'] as String?,
      ownerNameEn: json['ownerNameEn'] as String?,
      contactPhone: json['contactPhone'] as String?,
      contactEmail: json['contactEmail'] as String?,
      joinedDate: json['joinedDate'] as String?,
      joinedDateEn: json['joinedDateEn'] as String?,
      commissionPercent: (json['commissionPercent'] as num?)?.toDouble(),
      activeAdsCount: json['activeAdsCount'] as int?,
      underReviewAdsCount: json['underReviewAdsCount'] as int?,
      pendingReviewCount: json['pendingReviewCount'] as int?,
      financialWithdrawalAlert: json['financialWithdrawalAlert'] as String?,
      financialWithdrawalAlertEn: json['financialWithdrawalAlertEn'] as String?,
      violationNotice: json['violationNotice'] as String?,
      violationNoticeEn: json['violationNoticeEn'] as String?,
      recentAdvertisements: (json['recentAdvertisements'] as List<dynamic>?)
              ?.map((e) => MerchantAdvertisement(
                    title: e['title'] as String,
                    titleEn: e['titleEn'] as String,
                    reference: e['reference'] as String,
                    price: e['price'] as String,
                    status: MerchantAdvertisementStatus.values.firstWhere(
                      (s) => s.name == e['status'],
                      orElse: () => MerchantAdvertisementStatus.approved,
                    ),
                  ))
              .toList() ??
          const [],
      allAdvertisements: (json['allAdvertisements'] as List<dynamic>?)
              ?.map((e) => MerchantAdvertisement(
                    title: e['title'] as String,
                    titleEn: e['titleEn'] as String,
                    reference: e['reference'] as String,
                    price: e['price'] as String,
                    status: MerchantAdvertisementStatus.values.firstWhere(
                      (s) => s.name == e['status'],
                      orElse: () => MerchantAdvertisementStatus.approved,
                    ),
                  ))
              .toList() ??
          const [],
    );
  }
}
